"""E2E coverage for the SQL rules that lint a SQL macro body's relation slot reads."""

from __future__ import annotations

from pathlib import Path

import pytest

from tests.e2e.src.sqlbuild.cli.commands.main.compile.sql_macros._test_types import (
    SqlMacroBodyRulesTestCase,
)
from tests.e2e.src.sqlbuild.cli.commands.main.compile.sql_macros.helpers import (
    SQL_RULES,
    WEEKLY_ORDERS,
    output,
    rates_with_middle_cte,
    run_project,
)


@pytest.mark.parametrize(
    "test_case",
    [
        SqlMacroBodyRulesTestCase(
            description="a_plain_group_read_beside_bare_columns_passes_the_body_rules",
            files={
                **WEEKLY_ORDERS,
                **SQL_RULES,
                **rates_with_middle_cte(
                    "plain AS (SELECT @weekly.keys, orders, refunds FROM counted)"
                ),
            },
            expected_returncode=0,
            expected_fragments=("Project compiled",),
            expected_absent_fragments=("SQLCLEAN",),
        ),
        SqlMacroBodyRulesTestCase(
            description="plain_single_slot_and_undeclared_reads_through_the_relation_pass",
            files={
                **WEEKLY_ORDERS,
                **SQL_RULES,
                **rates_with_middle_cte(
                    "named AS (\n"
                    "  SELECT @weekly.refund_count AS refunds, @weekly.week AS week\n"
                    "  FROM @weekly\n"
                    "),\n\n"
                    "plain AS (SELECT @weekly.keys, orders, refunds FROM counted)"
                ),
            },
            expected_returncode=0,
            expected_fragments=("Project compiled",),
            expected_absent_fragments=("SQLCLEAN",),
        ),
        SqlMacroBodyRulesTestCase(
            description="a_real_mixed_qualification_beside_a_plain_group_read_is_reported",
            files={
                **WEEKLY_ORDERS,
                **SQL_RULES,
                **rates_with_middle_cte(
                    "plain AS (SELECT @weekly.keys, c.orders, refunds FROM counted AS c)"
                ),
            },
            expected_returncode=1,
            expected_fragments=(
                "error[SQLCLEAN028]: Single-relation query mixes qualified and unqualified columns "
                "(in SQL generated by @weekly)\n  --> macros/sql/weekly_rates.sql:14:18",
                "error[SQLCLEAN028]: Single-relation query mixes qualified and unqualified columns\n"
                "  --> macros/sql/weekly_rates.sql:14:42",
            ),
            expected_absent_fragments=("SQLCLEAN029",),
        ),
        SqlMacroBodyRulesTestCase(
            description="a_qualifier_absent_from_scope_beside_a_plain_group_read_is_reported",
            files={
                **WEEKLY_ORDERS,
                **SQL_RULES,
                **rates_with_middle_cte(
                    "plain AS (SELECT @weekly.keys, orders, refunds FROM counted)"
                ),
                "macros/sql/uncalled_rates.sql": (
                    'MACRO (\n  description "Weekly orders per grain",\n'
                    "  arguments (weekly RELATION (keys COLUMNS, order_count BIGINT)),\n);\n\n"
                    "WITH counted AS (\n"
                    "  SELECT s.@weekly.keys, s.@weekly.order_count AS orders FROM @weekly AS s\n"
                    "),\n\n"
                    "plain AS (SELECT @weekly.keys, x.orders FROM counted AS c)\n"
                ),
            },
            expected_returncode=1,
            expected_fragments=(
                "error[SQLCLEAN029]: Qualified reference uses a relation absent from this query "
                "scope\n  --> macros/sql/uncalled_rates.sql:10:32",
            ),
            expected_absent_fragments=(
                "error[SQLCLEAN029]: Qualified reference uses a relation absent from this query "
                "scope (in SQL generated by @weekly)",
                "--> macros/sql/weekly_rates.sql",
            ),
        ),
    ],
    ids=lambda case: case.description,
)
def test_given_slot_reads_in_a_macro_body_when_compiling_then_body_rules_judge_the_expansion(
    test_case: SqlMacroBodyRulesTestCase, tmp_path: Path
) -> None:
    _, result = run_project(tmp_path=tmp_path, files=test_case.files, command=("compile",))
    printed: str = output(result)

    assert result.returncode == test_case.expected_returncode, printed
    for fragment in test_case.expected_fragments:
        assert fragment in printed, printed
    for fragment in test_case.expected_absent_fragments:
        assert fragment not in printed, printed
