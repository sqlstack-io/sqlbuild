//! The registered Python names of the typed native ids, so native code never looks them up by string.

use crate::records::types::{ErrorId, NativeAttr, RecordId};

/// Each variant's declaration-order list and the Python name it is registered under.
macro_rules! native_id_names {
    ($name:ident { $($enum:ident::$variant:ident => $text:literal,)* }) => {
        impl $name {
            /// Every variant, in declaration order.
            pub const ALL: &'static [Self] = &[$($enum::$variant,)*];

            /// The attribute name the variant is registered under.
            pub const fn name(self) -> &'static str {
                match self {
                    $(Self::$variant => $text,)*
                }
            }
        }

        const _: () = {
            let mut index: usize = 0;
            while index < $name::ALL.len() {
                assert!(
                    $name::ALL[index] as usize == index,
                    "ALL must follow declaration order: lookups index tables by `id as usize`"
                );
                index += 1;
            }
        };
    };
}

