//! How a unit's nodes, checks and factories are declared: delegation, signature, factory shape and description.

use std::collections::BTreeSet;

use sqlbuild_pysource::node_units::models::{UnitDecorator, UnitFunction};

use crate::models::Fault;
use crate::python_rules::_helpers::units::project::{
    Declared, binds_module, declared, names_from_unit_modules, top_functions, unit_fault,
    unit_file_name, unit_imports,
};
use crate::python_rules::constants::{
    CHECK_KIND, CONTEXT_PARAMETER, DESCRIPTION_KEYWORD, FACTORY_SHAPE_CODE, LOADER_DECORATOR,
    MAIN_NAME, NAME_KEYWORD, NODE_DELEGATES_TO_MAIN_CODE, NODE_DESCRIPTION_CODE,
    NODE_SIGNATURE_CODE, SPEC_MODULES, UNIT_CHECKS_FILE, UNIT_NODE_FILE,
};
use crate::python_rules::models::{UnitFile, UnitProject};

/// The names a unit file imports from its unit's main.py and spec modules.
#[derive(Debug)]
struct UnitNames {
    main: BTreeSet<String>,
    specs: BTreeSet<String>,
}

/// Declaration faults of every node, check and factory in a unit's node.py and checks.py.
pub(crate) fn declaration_faults(project: &UnitProject<'_>) -> Vec<Fault> {
    let mut faults: Vec<Fault> = Vec::new();
    for file in &project.files {
        let (Some(unit), Some(UNIT_NODE_FILE | UNIT_CHECKS_FILE)) =
            (file.unit.as_deref(), unit_file_name(file))
        else {
            continue;
        };
        let names = UnitNames {
            main: unit_imports(file, project, unit, &[MAIN_NAME])
                .into_iter()
                .filter(|import| !binds_module(import, file, project))
                .map(|import| import.local.clone())
                .collect(),
            specs: names_from_unit_modules(file, project, unit, &SPEC_MODULES),
        };
        for function in top_functions(file) {
            match declared(function) {
                Some((Declared::Factory, _)) => {
                    faults.extend(factory_faults(file, function, &names));
                }
                Some((what, decorator)) => {
                    faults.extend(declaration_fault_list(
                        file,
                        function,
                        (what, decorator),
                        &names,
                    ));
                }
                None => {}
            }
        }
    }
    faults
}

/// The faults of one node or check declaration, top-level or generated by a factory.
fn declaration_fault_list(
    file: &UnitFile<'_>,
    function: &UnitFunction,
    (what, decorator): (Declared, &UnitDecorator),
    names: &UnitNames,
) -> Vec<Fault> {
    let mut details: Vec<(&str, String)> = Vec::new();
    if let Declared::Node(..) = what {
        details.extend(
            delegation_detail(function, names).map(|detail| (NODE_DELEGATES_TO_MAIN_CODE, detail)),
        );
    }
    let context: &str = match what {
        Declared::Node(_, context) => context,
        _ => CHECK_KIND.1,
    };
    details.extend(
        signature_details(function, context)
            .into_iter()
            .map(|detail| (NODE_SIGNATURE_CODE, detail)),
    );
    details.extend(
        description_detail(function, decorator).map(|detail| (NODE_DESCRIPTION_CODE, detail)),
    );
    details
        .iter()
        .filter_map(|(code, detail)| unit_fault(code, file.path, function.position, detail))
        .collect()
}

/// Why `function`'s body is not `return main(...)` with keyword arguments and `main` from its unit, if it is not.
fn delegation_detail(function: &UnitFunction, names: &UnitNames) -> Option<String> {
    let name: &str = &function.name;
    match function.delegation {
        None => Some(format!("'{name}' does not return main(...)")),
        Some(false) => Some(format!(
            "'{name}' passes main() an argument that is not name=value"
        )),
        Some(true) if !names.main.contains(MAIN_NAME) => Some(format!(
            "'{name}' calls a main() that is not imported from its unit's main.py"
        )),
        Some(true) => None,
    }
}

/// What is wrong with `function`'s parameters for a declaration whose `ctx` is a `context`.
fn signature_details(function: &UnitFunction, context: &str) -> Vec<String> {
    let name: &str = &function.name;
    let mut details: Vec<String> = Vec::new();
    match function.positional.as_slice() {
        [ctx] if ctx.name == CONTEXT_PARAMETER => {
            if ctx.annotation.as_deref() != Some(context) {
                details.push(format!("'{name}' does not annotate ctx as {context}"));
            }
        }
        _ => details.push(format!(
            "'{name}' does not take ctx as its only positional parameter"
        )),
    }
    if function.variadic || function.keywords_variadic {
        details.push(format!("'{name}' takes *args or **kwargs"));
    }
    details.extend(
        function
            .keyword_only
            .iter()
            .filter(|parameter| parameter.annotation.is_none())
            .map(|parameter| format!("'{name}' does not annotate provider '{}'", parameter.name)),
    );
    details
}

/// Why `function` sets a docstring or lacks description=, if it does.
fn description_detail(function: &UnitFunction, decorator: &UnitDecorator) -> Option<String> {
    let name: &str = &function.name;
    let described: bool = decorator
        .keywords
        .iter()
        .any(|keyword| keyword == DESCRIPTION_KEYWORD);
    if decorator.name == LOADER_DECORATOR {
        return (described || function.docstring)
            .then(|| format!("loader '{name}' sets a description or docstring"));
    }
    if function.docstring {
        return Some(format!("'{name}' has a docstring"));
    }
    (!described).then(|| format!("'{name}' does not set description="))
}

/// A factory's loops, generated names and generated declarations.
fn factory_faults(file: &UnitFile<'_>, factory: &UnitFunction, names: &UnitNames) -> Vec<Fault> {
    let mut details: Vec<String> = Vec::new();
    let reads_specs: bool = factory
        .loops
        .iter()
        .flatten()
        .any(|name| names.specs.contains(name));
    if factory.loops.is_empty() {
        details.push(format!(
            "factory '{}' does not loop over specs",
            factory.name
        ));
    } else if !reads_specs {
        details.push(format!(
            "factory '{}' loops over something that is not imported from its unit's constants.py or models.py",
            factory.name
        ));
    }
    let mut faults: Vec<Fault> = details
        .iter()
        .filter_map(|detail| unit_fault(FACTORY_SHAPE_CODE, file.path, factory.position, detail))
        .collect();
    for inner in &factory.inner {
        let Some((what, decorator)) = declared(inner) else {
            continue;
        };
        if !decorator
            .keywords
            .iter()
            .any(|keyword| keyword == NAME_KEYWORD)
        {
            faults.extend(unit_fault(
                FACTORY_SHAPE_CODE,
                file.path,
                inner.position,
                &format!("generated '{}' does not set name=", inner.name),
            ));
        }
        faults.extend(declaration_fault_list(
            file,
            inner,
            (what, decorator),
            names,
        ));
    }
    faults
}
