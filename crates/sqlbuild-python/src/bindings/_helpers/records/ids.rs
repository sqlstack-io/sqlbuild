//! Typed names of what `sqlbuild._native` registers, so native code never looks them up by string.

/// An enum of registered names with its declaration-order list and each variant's Python name.
macro_rules! native_ids {
    ($(#[$meta:meta])* $vis:vis enum $name:ident { $($variant:ident => $text:literal,)* }) => {
        $(#[$meta])*
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        $vis enum $name {
            $($variant,)*
        }

        impl $name {
            /// Every variant, in declaration order.
            pub(crate) const ALL: &'static [Self] = &[$(Self::$variant,)*];

            /// The attribute name the variant is registered under.
            pub(crate) const fn name(self) -> &'static str {
                match self {
                    $(Self::$variant => $text,)*
                }
            }
        }
    };
}

